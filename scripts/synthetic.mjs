// Deterministic synthetic project generator: N JavaScript files in folders of 50, layered
// (route → controller → service → model/util) with imports inside a module and a few across modules.
// Shared by `npm run gen:synthetic`, `npm run bench:scale` (Node) and the U3 frame-time check (Playwright).
// Same N always gives the same files, so numbers are comparable between runs.

/** A tiny seeded generator (LCG) so no run depends on Math.random. */
function rng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

const LAYERS = ['routes', 'controllers', 'services', 'models', 'utils'];
const PER_DIR = 50;

/**
 * @param {number} n number of source files (a package.json and a README come on top)
 * @returns {{ path: string; text: string }[]}
 */
export function generateSynthetic(n) {
  const rand = rng(1234 + n);
  const dirs = Math.max(1, Math.ceil(n / PER_DIR));
  /** @type {{ path: string; text: string }[]} */
  const files = [];
  /** @type {string[][]} paths per module, by index */
  const perModule = Array.from({ length: dirs }, () => []);
  for (let i = 0; i < n; i++) {
    const m = Math.floor(i / PER_DIR);
    const layer = LAYERS[i % LAYERS.length];
    perModule[m].push(`src/mod${String(m).padStart(3, '0')}/${layer}/f${i}.js`);
  }
  for (let m = 0; m < dirs; m++) {
    for (let k = 0; k < perModule[m].length; k++) {
      const path = perModule[m][k];
      const layerIdx = LAYERS.indexOf(path.split('/')[2]);
      const rel = (to) => {
        const a = path.split('/').slice(0, -1);
        const b = to.split('/');
        let i = 0;
        while (i < a.length && i < b.length - 1 && a[i] === b[i]) i++;
        return (a.length - i === 0 ? './' : '../'.repeat(a.length - i)) + b.slice(i).join('/');
      };
      // lower layers only (a route may use any layer below it), so the sample has real layering and few cycles
      const pool = perModule[m].filter((p) => LAYERS.indexOf(p.split('/')[2]) > layerIdx);
      const deps = new Set();
      for (let d = 0; d < 2 && pool.length; d++) deps.add(pool[Math.floor(rand() * pool.length)]);
      if (m > 0 && rand() < 0.15) {
        const other = perModule[Math.floor(rand() * m)];
        deps.add(other[Math.floor(rand() * other.length)]);
      }
      const name = path.split('/').pop().replace('.js', '');
      const lines = [];
      [...deps].forEach((d, i) => lines.push(`const dep${i} = require('${rel(d)}');`));
      if (layerIdx === 0) lines.push("const router = require('express').Router();");
      lines.push('');
      const branches = 1 + Math.floor(rand() * 6);
      lines.push(`function run_${name}(a, b) {`);
      lines.push('  let total = 0;');
      for (let b = 0; b < branches; b++) {
        lines.push(`  if (a > ${b} && b < ${b + 10}) {`);
        lines.push(`    for (let i = 0; i < a; i++) { total += i * ${b + 1}; }`);
        lines.push('  } else if (b) {');
        lines.push(`    total -= ${b};`);
        lines.push('  }');
      }
      [...deps].forEach((_, i) => lines.push(`  total += dep${i}.run ? dep${i}.run(a, b) : 0;`));
      lines.push('  return total;');
      lines.push('}');
      lines.push('');
      if (layerIdx === 0) {
        lines.push(`router.get('/mod${m}/f${k}', (req, res) => res.json({ v: run_${name}(1, 2) }));`);
        lines.push('module.exports = router;');
      } else {
        lines.push(`module.exports = { run: run_${name} };`);
      }
      lines.push('');
      files.push({ path, text: lines.join('\n') });
    }
  }
  files.push({ path: 'package.json', text: JSON.stringify({ name: `synthetic-${n}`, version: '1.0.0', main: 'src/mod000/routes/f0.js', dependencies: { express: '^4.19.0' }, scripts: { start: 'node src/mod000/routes/f0.js' } }, null, 2) });
  files.push({ path: 'README.md', text: `# synthetic-${n}\n\nGenerated by scripts/synthetic.mjs. ${n} files in ${dirs} folders.\n` });
  return files;
}

// CLI: node scripts/gen-synthetic.mjs <files> [out.zip]
export async function main(argv) {
  const n = Number(argv[0] ?? 10000);
  if (!Number.isFinite(n) || n < 1) throw new Error('usage: node scripts/gen-synthetic.mjs <files> [out.zip]');
  const { mkdirSync, writeFileSync } = await import('node:fs');
  const { dirname, resolve } = await import('node:path');
  const { zipSync, strToU8 } = await import('fflate');
  const out = resolve(argv[1] ?? `tests/bench/.synthetic/synthetic-${n}.zip`);
  const entries = Object.fromEntries(generateSynthetic(n).map((f) => [`synthetic-${n}/${f.path}`, strToU8(f.text)]));
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, zipSync(entries, { level: 1 }));
  console.log(`wrote ${out} (${Object.keys(entries).length} files)`);
}
