import type { SkipReason } from '../types';
import { basename, escapeRegExp, extname } from '../util';

interface Rule {
  neg: boolean;
  dirOnly: boolean;
  /** Matches the path itself. */
  exact: RegExp;
  /** Matches anything below the path. */
  under: RegExp;
}

function compile(pattern: string, base: string): Rule | null {
  let p = pattern.trim();
  if (!p || p.startsWith('#')) return null;
  let neg = false;
  if (p.startsWith('!')) {
    neg = true;
    p = p.slice(1);
  }
  const dirOnly = p.endsWith('/');
  if (dirOnly) p = p.slice(0, -1);
  const anchored = p.includes('/');
  if (p.startsWith('/')) p = p.slice(1);
  if (!p) return null;
  let body = '';
  for (let i = 0; i < p.length; i++) {
    const c = p[i];
    if (c === '*') {
      if (p[i + 1] === '*') {
        if (p[i + 2] === '/') {
          body += '(?:.*/)?';
          i += 2;
        } else {
          body += '.*';
          i += 1;
        }
      } else body += '[^/]*';
    } else if (c === '?') body += '[^/]';
    else body += escapeRegExp(c);
  }
  const prefix = (base ? escapeRegExp(base) + '/' : '') + (anchored ? '' : '(?:.*/)?');
  try {
    return { neg, dirOnly, exact: new RegExp('^' + prefix + body + '$'), under: new RegExp('^' + prefix + body + '/') };
  } catch {
    return null;
  }
}

/** gitignore-style matcher. Later rules override earlier ones; `!` re-includes. */
export class IgnoreMatcher {
  private rules: Rule[] = [];

  constructor(patterns: string[] = [], base = '') {
    this.add(patterns, base);
  }

  add(patterns: string[], base = ''): void {
    for (const p of patterns) {
      const r = compile(p, base);
      if (r) this.rules.push(r);
    }
  }

  get size(): number {
    return this.rules.length;
  }

  ignores(path: string, isDir = false): boolean {
    let ignored = false;
    for (const r of this.rules) {
      const hit = r.under.test(path) || (r.exact.test(path) && (!r.dirOnly || isDir));
      if (hit) ignored = !r.neg;
    }
    return ignored;
  }
}

const IMAGE_EXT = new Set(['.png', '.jpg', '.jpeg', '.gif', '.bmp', '.ico', '.webp', '.tiff', '.tif', '.psd', '.avif', '.heic', '.svg', '.icns']);
const BINARY_EXT = new Set([
  '.exe', '.dll', '.so', '.dylib', '.a', '.o', '.obj', '.lib', '.class', '.jar', '.war', '.ear', '.pyc', '.pyo',
  '.wasm', '.bin', '.dat', '.db', '.sqlite', '.sqlite3', '.pdf', '.doc', '.docx', '.xls', '.xlsx', '.ppt', '.pptx',
  '.tar', '.gz', '.tgz', '.bz2', '.xz', '.7z', '.rar', '.woff', '.woff2', '.ttf', '.otf', '.eot', '.mp3', '.mp4',
  '.mov', '.avi', '.mkv', '.wav', '.flac', '.ogg', '.webm', '.iso', '.dmg', '.apk', '.ipa', '.keystore', '.jks',
  '.p12', '.pfx', '.node', '.pdb', '.nupkg', '.snap', '.parquet', '.npy', '.pkl', '.h5', '.onnx', '.pt', '.tflite',
]);

/** Cheap, name-only classification done before any bytes are read. */
export function classifyByName(path: string): SkipReason | null {
  const ext = extname(path);
  if (ext === '.zip') return 'nested-zip';
  if (IMAGE_EXT.has(ext)) return 'image';
  if (BINARY_EXT.has(ext)) return 'binary';
  const base = basename(path);
  if (/\.min\.(js|css)$/.test(base) || /[.-]bundle\.js$/.test(base)) return 'minified';
  return null;
}

/** Minified / machine-packed text: very long lines with little whitespace. */
export function isMinified(text: string): boolean {
  if (text.length < 1500) return false;
  const sample = text.length > 200_000 ? text.slice(0, 200_000) : text;
  let lines = 1;
  let ws = 0;
  let maxLine = 0;
  let cur = 0;
  for (let i = 0; i < sample.length; i++) {
    const c = sample.charCodeAt(i);
    if (c === 10) {
      lines++;
      if (cur > maxLine) maxLine = cur;
      cur = 0;
    } else {
      cur++;
      if (c === 32 || c === 9) ws++;
    }
  }
  if (cur > maxLine) maxLine = cur;
  const avg = sample.length / lines;
  const wsRatio = ws / sample.length;
  if (maxLine > 30_000) return true;
  return avg > 300 && wsRatio < 0.2;
}

// Markers are matched case-sensitively and as whole words so that e.g. JPA's
// @GeneratedValue annotation does not make an entity look like generated code.
const GENERATED_MARK = /@generated\b|\bDO NOT EDIT\b|\bDO NOT MODIFY\b/;
const GENERATED_PHRASE = /\bcode generated by\b|\bauto-?generated (?:file|code|by)\b|\bautomatically generated\b|generated by the protocol buffer compiler|\bthis file (?:is|was) (?:auto-?)?generated\b/i;
export function isGenerated(text: string): boolean {
  const head = text.length > 1500 ? text.slice(0, 1500) : text;
  return GENERATED_MARK.test(head) || GENERATED_PHRASE.test(head);
}

