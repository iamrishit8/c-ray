import { describe, expect, it } from 'vitest';
import { zipSync, strToU8 } from 'fflate';
import { IgnoreMatcher, isGenerated, isMinified } from '../../src/core/ingest/filter';
import { ingest, IngestError } from '../../src/core/ingest/ingest';
import { runPipeline } from '../../src/core/pipeline';
import { DEFAULT_OPTIONS } from '../../src/core/types';
import { analyzeFixture, analyzeMem, FIXTURE_NAMES, groundTruth, memSource } from '../helpers';
import { nodeEnv } from '../../src/core/node-env';

describe('ignore matcher', () => {
  it('follows gitignore semantics', () => {
    const m = new IgnoreMatcher(['node_modules/', '*.log', '/build', 'docs/**/*.tmp', '!keep.log', 'src/gen/']);
    expect(m.ignores('node_modules/a/b.js')).toBe(true);
    expect(m.ignores('pkg/node_modules/x.js')).toBe(true);
    expect(m.ignores('a/debug.log')).toBe(true);
    expect(m.ignores('a/keep.log')).toBe(false);
    expect(m.ignores('build/out.js')).toBe(true);
    expect(m.ignores('sub/build/out.js')).toBe(false);
    expect(m.ignores('docs/a/b/c.tmp')).toBe(true);
    expect(m.ignores('src/gen/x.ts')).toBe(true);
    expect(m.ignores('src/main.ts')).toBe(false);
    expect(m.ignores('node_modules')).toBe(false); // dir-only pattern does not match a plain file
    expect(m.ignores('node_modules', true)).toBe(true);
  });
});

describe('content classification', () => {
  it('detects minified and generated text', () => {
    expect(isMinified('var a=1;'.repeat(2000))).toBe(true);
    expect(isMinified('const a = 1;\nconst b = 2;\n'.repeat(200))).toBe(false);
    expect(isGenerated('// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x')).toBe(true);
    expect(isGenerated('/** @generated */\nexport const x = 1;')).toBe(true);
    expect(isGenerated('export const x = 1;')).toBe(false);
  });
});

describe('ingestion', () => {
  it('filters ignored, binary, image, lock, minified, generated and oversized files with reasons', async () => {
    const res = await ingest(
      {
        kind: 'memory',
        files: [
          { path: 'proj/src/a.ts', text: 'export const a = 1;\n' },
          { path: 'proj/node_modules/x/index.js', text: 'module.exports = 1' },
          { path: 'proj/node_modules/y/index.js', text: 'module.exports = 2' },
          { path: 'proj/logo.png', bytes: new Uint8Array([137, 80, 78, 71]) },
          { path: 'proj/data.bin2', bytes: new Uint8Array([0, 1, 2, 0, 0, 5]) },
          { path: 'proj/package-lock.json', text: '{}' },
          { path: 'proj/app.min.js', text: 'x' },
          { path: 'proj/packed.js', text: 'var a=1;'.repeat(400) },
          { path: 'proj/gen.ts', text: '// @generated\nexport const g = 1;' },
          { path: 'proj/big.ts', text: 'x'.repeat(5000) },
          { path: 'proj/inner.zip', bytes: new Uint8Array([80, 75, 3, 4]) },
          { path: 'proj/.gitignore', text: 'secret/\n*.tmp\n' },
          { path: 'proj/secret/key.ts', text: 'export const k = 1;' },
          { path: 'proj/notes.tmp', text: 'hello' },
        ],
      },
      { ...DEFAULT_OPTIONS, maxFileBytes: 4000 },
    );
    expect(res.units.map((u) => u.path).sort()).toEqual(['.gitignore', 'src/a.ts']);
    const reason = (p: string) => res.skipped.find((s) => s.path === p)?.reason;
    expect(reason('node_modules/')).toBe('ignored');
    expect(res.skipped.find((s) => s.path === 'node_modules/')?.detail).toBe('2 files');
    expect(reason('logo.png')).toBe('image');
    expect(reason('data.bin2')).toBe('binary');
    expect(reason('package-lock.json')).toBe('lockfile');
    expect(reason('app.min.js')).toBe('minified');
    expect(reason('packed.js')).toBe('minified');
    expect(reason('gen.ts')).toBe('generated');
    expect(reason('big.ts')).toBe('too-large');
    expect(reason('inner.zip')).toBe('nested-zip');
    expect(reason('secret/key.ts')).toBe('gitignore');
    expect(reason('notes.tmp')).toBe('gitignore');
    expect(res.notices.some((n) => n.includes('Nested ZIP'))).toBe(true);
    expect(res.discovered).toBe(14);
  });

  it('reads ZIP archives (streaming) and strips the root folder', async () => {
    const zip = zipSync({ 'repo/src/index.js': strToU8('console.log(1)\n'), 'repo/README.md': strToU8('# Hi\n'), 'repo/node_modules/a.js': strToU8('1') });
    const res = await ingest({ kind: 'zip', file: new Blob([zip as BlobPart]), name: 'repo.zip' }, DEFAULT_OPTIONS);
    expect(res.units.map((u) => u.path)).toEqual(['README.md', 'src/index.js']);
    expect(res.skipped[0].reason).toBe('ignored');
  });

  it('rejects a corrupted ZIP with a clear error', async () => {
    const junk = new Uint8Array(2000).map((_, i) => (i * 7) % 251);
    await expect(ingest({ kind: 'zip', file: new Blob([junk]), name: 'bad.zip' }, DEFAULT_OPTIONS)).rejects.toBeInstanceOf(IngestError);
  });

  it('applies the total-bytes budget and reports coverage', async () => {
    const files: Record<string, string> = {};
    for (let i = 0; i < 20; i++) files[`src/f${i}.ts`] = `export const v${i} = ${i};\n`.repeat(40);
    const { analysis } = await runPipeline(memSource(files), 'budget', { maxTotalBytes: 6000 }, nodeEnv());
    expect(analysis.coverage.analyzed).toBeLessThan(20);
    expect(analysis.coverage.limited).toMatch(/prioritised subset/);
    expect(analysis.coverage.pctFiles).toBeLessThan(100);
    expect(analysis.skipped.some((s) => s.reason === 'budget')).toBe(true);
  });
});

describe('L0 on fixtures', () => {
  for (const name of FIXTURE_NAMES) {
    it(`${name}: languages, manifests and stack`, async () => {
      const gt = groundTruth(name);
      const { analysis: a } = await analyzeFixture(name);
      const langs = a.l0.languages.map((l) => l.lang);
      for (const l of gt.languages) expect(langs).toContain(l);
      const tech = a.l0.tech.map((t) => t.id);
      for (const fw of gt.frameworks) expect(tech).toContain(fw);
      for (const t of a.l0.tech) for (const e of t.evidence) expect(e.note.length).toBeGreaterThan(0);
      expect(a.files.every((f) => f.loc >= 0 && f.hash.length > 0)).toBe(true);
      expect(a.entries.map((x) => x.file)).toContain(gt.entryFiles[0]); // the full list is asserted with the detectors (M4)
      expect(a.orientation.summary.length).toBeGreaterThan(40);
      expect(a.orientation.readFirst.length).toBeGreaterThan(0);
      expect(a.gitMessage).toMatch(/\.git folder/);
    });
  }

  it('parses many manifest formats', async () => {
    const { analysis: a } = await analyzeMem({
      'pyproject.toml': '[project]\nname = "svc"\ndependencies = [\n  "fastapi>=0.110",\n  "sqlalchemy",\n]\n',
      'go.mod': 'module example.com/svc\n\ngo 1.22\n\nrequire (\n\tgithub.com/gin-gonic/gin v1.9.1\n)\n',
      'Cargo.toml': '[package]\nname = "tool"\n\n[dependencies]\naxum = "0.7"\n',
      'composer.json': '{"require": {"php": "^8.2", "laravel/framework": "^11.0"}}',
      'Gemfile': "source 'https://rubygems.org'\ngem 'rails', '~> 7.1'\ngem 'sidekiq'\n",
      'Api/Api.csproj': '<Project Sdk="Microsoft.NET.Sdk.Web">\n<ItemGroup>\n<PackageReference Include="Microsoft.EntityFrameworkCore" Version="8.0.0" />\n</ItemGroup>\n</Project>',
      'build.gradle': "plugins {\n  id 'org.springframework.boot' version '3.2.0'\n}\ndependencies {\n  implementation 'org.springframework.boot:spring-boot-starter-web'\n}\n",
      'Dockerfile': 'FROM python:3.12\n',
      '.github/workflows/ci.yml': 'name: CI\non: push\n',
      'k8s/deploy.yaml': 'apiVersion: apps/v1\nkind: Deployment\n',
      '.env.example': 'DATABASE_URL=\n',
    });
    const tech = a.l0.tech.map((t) => t.id);
    for (const id of ['fastapi', 'sqlalchemy', 'gin', 'axum', 'laravel', 'rails', 'sidekiq', 'aspnet', 'efcore', 'spring-boot', 'docker', 'ci', 'kubernetes']) {
      expect(tech, id).toContain(id);
    }
    expect(a.l0.configs.map((c) => c.kind).sort()).toEqual(['ci', 'docker', 'env', 'k8s']);
    expect(a.l0.manifests.find((m) => m.type === 'go.mod')?.name).toBe('example.com/svc');
  });

  it('single file input switches to File Mode', async () => {
    const { analysis: a } = await analyzeMem({ 'solo.py': 'def f():\n    return 1\n' });
    expect(a.mode).toBe('file');
    expect(a.orientation.summary).toMatch(/architecture views need more files/);
  });

  it('never crashes on empty / binary-only input', async () => {
    const empty = await runPipeline({ kind: 'memory', files: [] }, 'empty', {}, nodeEnv());
    expect(empty.analysis.files).toHaveLength(0);
    const bin = await runPipeline({ kind: 'memory', files: [{ path: 'a.exe', bytes: new Uint8Array([0, 0, 1]) }, { path: 'b.dat', bytes: new Uint8Array(100) }] }, 'bin', {}, nodeEnv());
    expect(bin.analysis.files).toHaveLength(0);
    expect(bin.analysis.skipped).toHaveLength(2);
  });
});

describe('generated-file detection edge cases', () => {
  it('does not mistake @GeneratedValue (JPA) for a generated-file marker', () => {
    expect(isGenerated('package x;\nimport jakarta.persistence.GeneratedValue;\n@Entity class A { @Id @GeneratedValue Long id; }')).toBe(false);
    expect(isGenerated('# This file is auto-generated by the build. Changes will be lost.')).toBe(true);
  });
});
